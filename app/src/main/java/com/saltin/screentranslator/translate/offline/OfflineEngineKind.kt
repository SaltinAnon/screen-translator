package com.saltin.screentranslator.translate.offline

/**
 * 端侧离线翻译引擎的**三档**（v1.6.2 重新设计为「覆盖面递进」）。
 *
 * ## 三档的定位（用户明确要求，别改回去）
 *
 * | 档位 | 引擎 | 覆盖 | 直译能力 | 体积 |
 * | --- | --- | --- | --- | --- |
 * | [ML_KIT] | Google 端侧 | 59 种语言 | 非英语之间经英语中转 | 约 30MB / 对 |
 * | [OPUS_MT] | Opus-MT 标准 | 常见方向 | **中↔英 / 中↔日 / 韩→英… 直译** | 约 115MB / 对 |
 * | [OPUS_FULL] | Opus-MT 全覆盖 | 最全 | 直译优先，缺的方向英语接力 | 约 115MB / 对（可两对） |
 *
 * 三档的关系是**覆盖面从窄到宽层层递进**，而不是「第二档是个残废、第三档才是完整版」：
 *
 * - **每一档都能独立翻译**，不存在「选了某档却完全不能用」。选窄档只会「可翻的方向少」，
 *   绝不会出现「连一个有匹配语言对的方向都翻不了」。
 * - 越往上**方向越多、直译越全**：第三档在第一档/第二档的全部能力之上，再多出接力兜底。
 *
 * ## 用户为什么投诉旧设计（v1.6.1 的错误）
 *
 * v1.6.1 把第二档设成「**只允许直译、不许接力**」，第三档设成「允许接力」。
 * 后果是：第二档看起来「连没有匹配语言对的方向都翻不了」，
 * 而第三档其实就是原来的第二档能力 —— 用户的原话是
 * 「目前第三档我发现就是原来的第二档，第二档降级为不能翻译没有匹配的语言对，我想要的不是这样」。
 *
 * 正确做法是：**第二档也要能翻**。它的定位应该是「常见方向 **直译**，质量最好」，
 * 而不是「只认直译、缺方向就拒」。于是现在的分工是：
 *
 * - 第二档：常见方向直译 + **必要时的英语接力**（能翻就一定翻出来，不留空档）；
 * - 第三档：在第二档之上，**把语言对扩到最全**（含旧版未收录的方向）。
 *
 * ## 直译优先（用户核心诉求）
 *
 * 用户要求「**中英中日中韩这些主要的至少需要直译，而不是中转**」。
 * 所以两张直译表都**优先**命中直译：只有直译模型确实不存在时才退到英语接力。
 * v1.6.2 新增了 `zh→ja` 的 tc-big 直译模型（BLEU 24.6，远好于 ja↔en↔zh 两跳），
 * 见 [OfflineModelCatalog] 的 `OPUS_TC_BIG_DIRECT`。
 */
enum class OfflineEngineKind(
    val id: String,
    val label: String,
    val shortLabel: String,
    val detail: String,
) {
    ML_KIT(
        "mlkit",
        "标准 · ML Kit（默认）",
        "标准",
        "Google 的端侧翻译，每个语言对约 30MB，速度最快（几十毫秒）。" +
            "覆盖 59 种语言，但非英语之间（如日→中）要靠英语中转两次，译文会比较生硬。",
    ),
    OPUS_MT(
        "opus_mt",
        "增强 · Opus-MT（直译）",
        "增强",
        "Helsinki-NLP 的开源翻译模型，每个语言对约 115MB，亚秒级速度。" +
            "**常见方向直接对译**（中↔英、中→日、英↔日韩法德西俄…），一次到位、不经英语中转，" +
            "质量明显好于 ML Kit。没有直译模型的方向会自动用英语快速接力，**依然能翻**。",
    ),
    OPUS_FULL(
        "opus_full",
        "全能 · Opus-MT 全覆盖",
        "全能",
        "与「增强」同一套 Opus-MT 模型（每对约 115MB、亚秒级），" +
            "但**可用方向放到最全**：有直译对就用直译，上游确实没训过的方向（如日→中）" +
            "才用英语**快速接力**（两段合计约 0.3 秒）。**没有 870MB 的大模型**，所以一样快。",
    ),
    ;

    /** 是否需要额外下载模型才能用（ML Kit 走它自己的按语言对下载流程） */
    val needsManagedModels: Boolean get() = this != ML_KIT

    /** 这一档是否允许「英语接力」兜底。第二、三档都允许 —— 这是「每档都能独立翻」的关键 */
    val allowsPivot: Boolean get() = this != ML_KIT

    companion object {
        fun fromId(id: String?): OfflineEngineKind =
            entries.firstOrNull { it.id == id } ?: ML_KIT
    }
}
